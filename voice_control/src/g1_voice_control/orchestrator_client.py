"""Thin client for the real orchestrator services. ROS-dependent.

Maps each confirmable voice command to the orchestrator interface currently
declared by this package. Re-check these constants and request fields against
the target workspace before enabling real dispatch; see README.md. "cancel"
has no mapping here and dispatch.py's cancel handling never calls this module.
"""

from __future__ import annotations

import threading
from typing import Optional

try:
    import rospy
except ImportError as exc:  # pragma: no cover - exercised only off-robot
    rospy = None
    _ROSPY_IMPORT_ERROR = exc
else:
    _ROSPY_IMPORT_ERROR = None

from g1_voice_control.dispatch import RouteCallResult

# Declared mapping. Validate against the target RunRoute.srv and terminal entry
# point before enabling real dispatch.
COMMAND_TO_SERVICE = {
    "grasp": "/orchestrator/run_grasp",
    "deliver": "/orchestrator/run_deliver",
    # The spoken task: target = pickup standing waypoint, destination =
    # delivery standing waypoint, label = perception class.
    "fetch_deliver": "/orchestrator/run_fetch_deliver",
}
COMMAND_TO_ROUTE_NAME = {
    "grasp": "grasp",
    "deliver": "deliver",
    "fetch_deliver": "fetch_deliver",
}
STATUS_TOPIC = "/orchestrator/status"


def _require_rospy() -> None:
    if rospy is None:
        raise RuntimeError(
            "rospy is not importable (are you running this outside a ROS "
            f"environment?): {_ROSPY_IMPORT_ERROR}"
        )


class RosRouteClient:
    """Implements dispatch.RouteClient against the real orchestrator.

    Service proxies are created lazily (first call), not at construction, so
    building this object does not itself require a ROS master -- only
    calling it does. That keeps `voice_control_node.py` able to start the
    mic/ASR pipeline and report "orchestrator unreachable" per command
    instead of failing at startup if the orchestrator node is not up yet.
    """

    def __init__(self, service_wait_timeout_s: float = 10.0) -> None:
        _require_rospy()
        self._service_wait_timeout_s = float(service_wait_timeout_s)
        self._proxies: dict = {}
        self._lock = threading.Lock()

    def _proxy(self, command_id: str):
        from orchestrator.srv import RunRoute  # generated by catkin; orchestrator must be built

        service_name = COMMAND_TO_SERVICE[command_id]
        with self._lock:
            proxy = self._proxies.get(command_id)
            if proxy is None:
                rospy.wait_for_service(service_name, timeout=self._service_wait_timeout_s)
                proxy = rospy.ServiceProxy(service_name, RunRoute)
                self._proxies[command_id] = proxy
            return proxy

    def call_route(self, command_id: str, target: str, dry_run: bool,
                   destination: str = "", label: str = "") -> RouteCallResult:
        if command_id not in COMMAND_TO_SERVICE:
            # Defensive: dispatch.py should never reach here for an
            # unmapped command, but refuse loudly rather than guess a
            # service name if it ever does.
            raise ValueError(f"no orchestrator service mapped for command {command_id!r}")

        proxy = self._proxy(command_id)
        resp = proxy(
            route=COMMAND_TO_ROUTE_NAME[command_id],
            target=target,
            # fetch_deliver carries both standing waypoints and the perception
            # label; the single-route commands leave them empty (the
            # orchestrator then falls back to its own defaults).
            destination=destination or "",
            label=label or "",
            start_step="",
            dry_run=bool(dry_run),
            event_token="",
        )
        return RouteCallResult(
            success=bool(resp.success),
            message=resp.message,
            blockers=tuple(resp.blockers),
            dry_run=bool(resp.dry_run),
            motion_issued=bool(resp.motion_issued),
        )


class StatusReader:
    """Caches the latest /orchestrator/status message (std_msgs/String,
    latched). Subscribes once; `status` is deliberately a read, so this
    never shares the Dispatcher's confirm/busy state machine."""

    def __init__(self) -> None:
        _require_rospy()
        from std_msgs.msg import String

        self._latest: Optional[str] = None
        self._lock = threading.Lock()
        self._sub = rospy.Subscriber(STATUS_TOPIC, String, self._on_status)

    def _on_status(self, msg) -> None:
        with self._lock:
            self._latest = msg.data

    def latest(self) -> str:
        with self._lock:
            if self._latest is None:
                return "no status received yet (orchestrator node may not be up)"
            return self._latest
